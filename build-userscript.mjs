// Builds no-shorts.user.js from the extension files (content.css + content.js).
// Run after editing either of them:  node build-userscript.mjs
import { readFileSync, writeFileSync } from "node:fs";

const { version, description } = JSON.parse(readFileSync("manifest.json", "utf8"));
const css = readFileSync("content.css", "utf8").replace(/[`\\$]/g, "\\$&");
const js = readFileSync("content.js", "utf8");
const raw = "https://raw.githubusercontent.com/290990-collab/no-shorts/main/no-shorts.user.js";

const out = `// ==UserScript==
// @name         No Shorts
// @namespace    https://github.com/290990-collab/no-shorts
// @version      ${version}
// @description  ${description}
// @homepageURL  https://github.com/290990-collab/no-shorts
// @downloadURL  ${raw}
// @updateURL    ${raw}
// @license      MIT
// @match        *://*.youtube.com/*
// @run-at       document-start
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_addValueChangeListener
// @grant        GM_registerMenuCommand
// @grant        GM_unregisterMenuCommand
// @noframes
// ==/UserScript==

// Generated by build-userscript.mjs. Edit content.css / content.js instead.

(() => {
  const style = document.createElement("style");
  style.textContent = \`
${css}\`;
  (document.head || document.documentElement).appendChild(style);
})();

// Optional extras live in the Violentmonkey menu (click its icon on a YouTube tab).
// Shorts are not in the menu: they are always blocked.
const NO_SHORTS_STORE = (() => {
  const LABELS = {
    comments: "Hide comments",
    chat: "Hide live chat",
    related: "Hide related videos",
    endscreen: "Hide end screen suggestions",
    homefeed: "Hide home feed",
  };
  const ids = {};
  const drawMenu = () => {
    for (const key of Object.keys(LABELS)) {
      if (ids[key] !== undefined && typeof GM_unregisterMenuCommand === "function") {
        GM_unregisterMenuCommand(ids[key]);
      }
      const on = GM_getValue(key, false) === true;
      ids[key] = GM_registerMenuCommand((on ? "☑ " : "☐ ") + LABELS[key], () => {
        GM_setValue(key, !on);
      });
    }
  };
  if (window.top === window) drawMenu();
  return {
    load: (keys, cb) => cb(Object.fromEntries(keys.map((k) => [k, GM_getValue(k, false)]))),
    watch: (cb) => {
      for (const key of Object.keys(LABELS)) {
        GM_addValueChangeListener(key, (_name, _old, value) => {
          cb({ [key]: value });
          if (window.top === window) drawMenu();
        });
      }
    },
  };
})();

${js}`;

writeFileSync("no-shorts.user.js", out);
console.log("no-shorts.user.js built, version " + version);
