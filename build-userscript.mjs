// Builds no-shorts.user.js from the extension files (content.css + content.js).
// Run after editing either of them:  node build-userscript.mjs
import { readFileSync, writeFileSync } from "node:fs";

const { version, description } = JSON.parse(readFileSync("manifest.json", "utf8"));
const css = readFileSync("content.css", "utf8").replace(/[`\\$]/g, "\\$&");
const js = readFileSync("content.js", "utf8");
const raw = "https://raw.githubusercontent.com/290990-collab/no-shorts/main/no-shorts.user.js";

const out = `// ==UserScript==
// @name         No Shorts
// @namespace    https://github.com/290990-collab/no-shorts
// @version      ${version}
// @description  ${description}
// @homepageURL  https://github.com/290990-collab/no-shorts
// @downloadURL  ${raw}
// @updateURL    ${raw}
// @license      MIT
// @match        *://*.youtube.com/*
// @run-at       document-start
// @grant        none
// @noframes
// ==/UserScript==

// Generated by build-userscript.mjs. Edit content.css / content.js instead.

(() => {
  const style = document.createElement("style");
  style.textContent = \`
${css}\`;
  (document.head || document.documentElement).appendChild(style);
})();

${js}`;

writeFileSync("no-shorts.user.js", out);
console.log("no-shorts.user.js built, version " + version);
